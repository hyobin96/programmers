# 3진법?
# 1 2 4 -> 1 2 3
# 1 -> 1, 2 -> 2, 3 -> 10, 4 -> 11, 5 -> 12, 6 -> 20
# 1 -> 1, 2 -> 2, 3 -> 4, 4 -> 11, 5 -> 12, 6 -> 14
# 1, 2, 3 을 가진 3진법으로 바꾸고 마지막에 3을 4로 변환?
# 1, 2, 4 로 생각하면 ... 3으로 나눴을 때 나머지가 1이면 1, 2면 2, 0이면 4?

def solution(n):
    n_to_124 = []
    
    while n > 0:
        나머지 = n % 3
        if 나머지 == 0:
            나머지 = 4
            n -= 1
        n_to_124.append(str(나머지))
        n //= 3
    
    answer = ''.join(n_to_124[::-1])
    return answer