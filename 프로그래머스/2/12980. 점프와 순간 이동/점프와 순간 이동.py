# 6... 1 -> 2 -> 3 -> 6
# 역으로 ... 2로 나누어지면 나누고, 아니면 -1
# 6 -> 3 -> 2 -> 1 -> 0
# 5000 -> 2500 -> 1250 -> 625 -> 624 -> 312 -> 156 -> 78 -> 39 -> 38 -> 19 -> 18 -> 9 -> 8 -> 4 -> 2 -> 1 -> 0
def solution(n):
    cnt = 0
    while n != 0:
        if n % 2 == 0:
            n //= 2
        else:
            n -= 1
            cnt += 1
            
    ans = cnt
    return ans